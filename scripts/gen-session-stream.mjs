#!/usr/bin/env node
/**
 * Generate agent/.../SessionStream.scala from sessionStream.ts.
 * Usage: node scripts/gen-session-stream.mjs [--check]
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tsPath = join(here, '../packages/core/bridge/protocol/src/sessionStream.ts');
const scalaPath = join(
	here,
	'../../agent/modules/runtime/bridge/src/main/scala/ai/fastllm/agent/bridge/SessionStream.scala'
);

const src = readFileSync(tsPath, 'utf8');
const match = src.match(/export const SESSION_STREAM_EVENT_TYPES = \[([\s\S]*?)\] as const/);
if (!match) {
	console.error('SESSION_STREAM_EVENT_TYPES array not found in sessionStream.ts');
	process.exit(1);
}
const types = [...match[1].matchAll(/'([^']+)'/g)].map(m => m[1]);
if (types.length === 0) {
	console.error('no event types parsed from sessionStream.ts');
	process.exit(1);
}

const quoted = types.map(t => `"${t}"`).join(',\n    ');
const generated = `// GENERATED by fast/scripts/gen-session-stream.mjs — do not edit.
package ai.fastllm.agent.bridge

object SessionStream:
  val types: Set[String] = Set(
    ${quoted}
  )
`;

const check = process.argv.includes('--check');
if (check) {
	let current = '';
	try {
		current = readFileSync(scalaPath, 'utf8');
	} catch {
		console.error(`missing ${scalaPath}`);
		process.exit(1);
	}
	if (current !== generated) {
		console.error('SessionStream.scala is stale — run: node fast/scripts/gen-session-stream.mjs');
		process.exit(1);
	}
	process.exit(0);
}

writeFileSync(scalaPath, generated);
console.log(`wrote ${types.length} types to ${scalaPath}`);
